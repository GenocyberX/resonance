  /**
   * Retrieves matching solid 16-bit pixel sprite for a given scenery definition and biome.
   */
  public static getScenerySprite(spriteId: string, biomeId: string): PixelSprite {
    const idLower = spriteId.toLowerCase();

    // Glacial / Alpine pass - STRICTLY Snow Pines
    if (biomeId === 'ALPINE' || idLower.includes('snow') || idLower.includes('ice') || idLower.includes('glacial')) {
      return PixelSpriteCatalog.SNOW_PINE_16BIT;
    }

    // Desert / Canyon - STRICTLY Saguaro Cactus
    if (biomeId === 'DESERT' || idLower.includes('cactus') || idLower.includes('saguaro') || idLower.includes('joshua')) {
      return PixelSpriteCatalog.SAGUARO_16BIT;
    }

    // Default to Tropical OutRun Fan Palm
    return PixelSpriteCatalog.PALM_OUTRUN_16BIT;
  }
