  /**
   * Retrieves matching solid 16-bit pixel sprite for a given scenery definition id.
   */
  public static getScenerySprite(spriteId: string, biomeId: string): PixelSprite {
    const idLower = spriteId.toLowerCase();
    if (idLower.includes('palm') || idLower.includes('tropical') || (idLower.includes('tree') && biomeId === 'TROPICAL')) {
      return PixelSpriteCatalog.PALM_OUTRUN_16BIT;
    }
    if (idLower.includes('sign') || idLower.includes('arrow') || idLower.includes('marker') || idLower.includes('curve') || idLower.includes('direction')) {
      return PixelSpriteCatalog.CURVE_SIGN_16BIT;
    }
    if (idLower.includes('cactus') || idLower.includes('saguaro') || idLower.includes('joshua') || biomeId === 'DESERT') {
      return PixelSpriteCatalog.SAGUARO_16BIT;
    }

    // Default to Biome specific 16-bit sprite
    switch (biomeId) {
      case 'TROPICAL': return PixelSpriteCatalog.PALM_OUTRUN_16BIT;
      case 'DESERT': return PixelSpriteCatalog.SAGUARO_16BIT;
      default: return PixelSpriteCatalog.PALM_OUTRUN_16BIT;
    }
  }
