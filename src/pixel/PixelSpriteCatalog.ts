  /**
   * Retrieves matching solid pixel sprite for a given scenery definition id.
   */
  public static getScenerySprite(spriteId: string, biomeId: string): PixelSprite {
    const idLower = spriteId.toLowerCase();
    if (idLower.includes('palm') || idLower.includes('beach') || idLower.includes('tropical') || idLower.includes('hotel') || idLower.includes('hut')) {
      return PixelSpriteCatalog.PALM_TREE;
    }
    if (idLower.includes('cactus') || idLower.includes('canyon') || idLower.includes('mesa') || idLower.includes('butte') || idLower.includes('dune')) {
      return PixelSpriteCatalog.SAGUARO_CACTUS;
    }
    if (idLower.includes('snow') || idLower.includes('ice') || idLower.includes('glacial') || idLower.includes('peak')) {
      return PixelSpriteCatalog.SNOW_PINE;
    }
    if (idLower.includes('cyber') || idLower.includes('neon') || idLower.includes('spire') || idLower.includes('gantry') || idLower.includes('totem')) {
      return PixelSpriteCatalog.CYBER_SPIRE;
    }
    if (idLower.includes('basalt') || idLower.includes('obsidian') || idLower.includes('volcanic') || idLower.includes('crag')) {
      return PixelSpriteCatalog.BASALT_CRAG;
    }

    // Default to Biome specific sprite
    switch (biomeId) {
      case 'TROPICAL': return PixelSpriteCatalog.PALM_TREE;
      case 'DESERT': return PixelSpriteCatalog.SAGUARO_CACTUS;
      case 'FOREST': return PixelSpriteCatalog.PINE_TREE;
      case 'ALPINE': return PixelSpriteCatalog.SNOW_PINE;
      case 'NEON_CITY': return PixelSpriteCatalog.CYBER_SPIRE;
      case 'VOLCANIC': return PixelSpriteCatalog.BASALT_CRAG;
      default: return PixelSpriteCatalog.PINE_TREE;
    }
  }
